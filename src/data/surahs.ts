export interface Surah {
  number: number;
  arabicName: string;
  banglaName: string;
  transliteration: string;
  ayahCount: number;
  revelationType: 'মাক্কী' | 'মাদানী';
  meaningBangla: string;
  juz: number;
  // Aliases for compatibility
  id: number;
  nameArabic: string;
  nameBangla: string;
  nameEnglish: string;
  totalAyahs: number;
  type: 'makkah' | 'madinah' | 'মাক্কী' | 'মাদানী';
}

export const BANG_NUMBERS = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];

export function toBanglaNumber(num: number | string): string {
  return String(num).replace(/[0-9]/g, (digit) => BANG_NUMBERS[parseInt(digit, 10)]);
}

// Helper to format Surah data consistently
function createSurah(
  number: number,
  arabicName: string,
  banglaName: string,
  transliteration: string,
  meaningBangla: string,
  ayahCount: number,
  revelationType: 'মাক্কী' | 'মাদানী',
  juz: number
): Surah {
  return {
    number,
    arabicName,
    banglaName,
    transliteration,
    ayahCount,
    revelationType,
    meaningBangla,
    juz,
    // Aliases
    id: number,
    nameArabic: arabicName,
    nameBangla: banglaName,
    nameEnglish: transliteration,
    totalAyahs: ayahCount,
    type: revelationType === 'মাক্কী' ? 'makkah' : 'madinah',
  };
}

